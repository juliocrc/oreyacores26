async function buildLatestInspectionSummaryForOrders(serializedOrders: ReturnType<typeof serializeOrder>[]) {
  const allJangadas = serializedOrders.flatMap((order) => Array.isArray(order?.jangadas) ? order.jangadas : []);
  const jangadaIds = Array.from(new Set(
    allJangadas
      .map((jangada) => Number(jangada?.id))
      .filter((id) => Number.isFinite(id) && id > 0)
  ));

  if (jangadaIds.length === 0) {
    return serializedOrders;
  }

  const inspections = await prisma.inspecao.findMany({
    where: {
      jangadaId: { in: jangadaIds },
    },
    orderBy: [{ dataInspecao: "desc" }, { updatedAt: "desc" }, { id: "desc" }],
    select: {
      id: true,
      jangadaId: true,
      certificadoNumero: true,
      dataInspecao: true,
      dataProxInspecao: true,
      status: true,
      testeWP: true,
      testeNAP: true,
      testeFS: true,
      testeGI: true,
      testeDL: true,
      artigos: {
        select: {
          id: true,
          name: true,
          referencia: true,
          quantidade: true,
        },
      },
    },
  });

  const latestInspectionByJangada = new Map<number, (typeof inspections)[number]>();
  for (const inspection of inspections) {
    const jangadaId = Number(inspection.jangadaId);
    if (!Number.isFinite(jangadaId) || jangadaId <= 0 || latestInspectionByJangada.has(jangadaId)) {
      continue;
    }
    latestInspectionByJangada.set(jangadaId, inspection);
  }

  return serializedOrders.map((order) => {
    const jangadas = Array.isArray(order?.jangadas) ? order.jangadas : [];
    const latestInspectionContext = jangadas.map((jangada) => {
      const inspection = latestInspectionByJangada.get(Number(jangada?.id));
      const hasReprovado = (value: string | null) => {
        const v = String(value || "").trim().toUpperCase();
        return v === "REPROVOU" || v === "REPROVADO";
      };
      const testesReprovados = inspection ? [
        hasReprovado(inspection.testeWP) ? "WP" : null,
        hasReprovado(inspection.testeNAP) ? "NAP" : null,
        hasReprovado(inspection.testeFS) ? "FS" : null,
        hasReprovado(inspection.testeGI) ? "GI" : null,
        hasReprovado(inspection.testeDL) ? "DL" : null,
      ].filter(Boolean) : [];

      return {
        jangadaId: Number(jangada?.id),
        serial: jangada?.serial || "",
        brand: jangada?.brand || null,
        model: jangada?.model || null,
        certificadoNumero: inspection?.certificadoNumero || null,
        dataInspecao: inspection?.dataInspecao || null,
        dataProxInspecao: inspection?.dataProxInspecao || null,
        status: inspection?.status || null,
        testes: {
          WP: inspection?.testeWP || null,
          NAP: inspection?.testeNAP || null,
          FS: inspection?.testeFS || null,
          GI: inspection?.testeGI || null,
          DL: inspection?.testeDL || null,
        },
        testesReprovados,
        artigosSubstituidosCount: Array.isArray(inspection?.artigos) ? inspection.artigos.length : 0,
        artigos: Array.isArray(inspection?.artigos)
          ? inspection.artigos.map((a) => ({ id: a.id, name: a.name, referencia: a.referencia, quantidade: a.quantidade }))
          : [],
      };
    });

    const historyCount = latestInspectionContext.filter((item) => item.dataInspecao).length;
    const replacementCount = latestInspectionContext.reduce((acc, item) => acc + Number(item.artigosSubstituidosCount || 0), 0);
    const totalTestesReprovados = latestInspectionContext.reduce((acc, item) => acc + (item.testesReprovados?.length || 0), 0);

    return {
      ...order,
      latestInspectionContext,
      latestInspectionSummary: {
        historyCount,
        replacementCount,
        totalTestesReprovados,
        latestDate: latestInspectionContext
          .map((item) => String(item.dataInspecao || "").trim())
          .filter(Boolean)
          .sort((a, b) => b.localeCompare(a))[0] || null,
      },
    };
  });
}

