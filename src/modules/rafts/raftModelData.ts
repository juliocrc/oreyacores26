function normalizeRaftLookupValue(value?: string | null) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, ' ')
    .trim();
}

const OPERATIONAL_TORCH_ITEM: RaftTechnicalItem = {
  name: 'Waterproof Torch',
  category: 'SINALIZAÇÃO',
};

const OPERATIONAL_TORCH_BATTERIES_ITEM: RaftTechnicalItem = {
  name: 'Torch Batteries',
  category: 'ILUMINAÇÃO',
  quantity: '4x',
  reference: '20903168',
  notes: 'Regra operacional: substituir em todas as inspeções e controlar validade.',
};

function isSosLikeOperationalModel(brand?: string | null, model?: string | null) {
  const normalizedBrand = normalizeRaftLookupValue(brand);
  const normalizedModel = normalizeRaftLookupValue(model);
  return normalizedBrand.includes('SOS') || normalizedModel.includes('SOS');
}

function hasPackItem(items: RaftTechnicalItem[], candidate: string) {
  const normalizedCandidate = normalizeRaftLookupValue(candidate);
  return items.some((item) => normalizeRaftLookupValue(item.name) === normalizedCandidate);
}

function augmentOperationalPackEquipment(
  packEquipment: RaftPackEquipment[] | undefined,
  brand?: string | null,
  model?: string | null,
) {
  if (!packEquipment || packEquipment.length === 0) return packEquipment;
  if (isSosLikeOperationalModel(brand, model)) return [] as RaftPackEquipment[];

  return packEquipment.map((pack) => {
    const normalizedPack = normalizeRaftLookupValue(pack.pack);
    if (normalizedPack.includes('SIMPLIFICADO MINIMO')) {
      return {
        ...pack,
        items: pack.items.map((item) => ({ ...item })),
      };
    }

    const items = pack.items.map((item) => ({ ...item }));
    if (!hasPackItem(items, OPERATIONAL_TORCH_ITEM.name)) items.push({ ...OPERATIONAL_TORCH_ITEM });
    if (!hasPackItem(items, OPERATIONAL_TORCH_BATTERIES_ITEM.name)) items.push({ ...OPERATIONAL_TORCH_BATTERIES_ITEM });

    return {
      ...pack,
      items,
    };
  });
}

function augmentOperationalTechnicalModel(
  entry: RaftModelEntry | null,
  brand?: string | null,
  model?: string | null,
) {
  if (!entry) return null;

  if (isSosLikeOperationalModel(brand, model)) {
    return {
      ...entry,
      packTypes: [],
      packEquipment: [],
    };
  }

  return {
    ...entry,
    packEquipment: augmentOperationalPackEquipment(entry.packEquipment, brand, model),
  };
}

export function findRaftTechnicalModel(brand?: string | null, model?: string | null) {
  const normalizedBrand = normalizeRaftLookupValue(brand);
  const normalizedModel = normalizeRaftLookupValue(model);
  if (!normalizedBrand || !normalizedModel) return null;

  const brandEntry = Object.entries(raftModelData).find(([key]) => normalizeRaftLookupValue(key) === normalizedBrand);
  if (!brandEntry) return null;

  const [, models] = brandEntry;
  const exact = models.find((entry) => normalizeRaftLookupValue(entry.name) === normalizedModel);
  if (exact) return augmentOperationalTechnicalModel(exact, brand, model);

  const aliasMatch = models.find((entry) =>
    (entry.aliases || []).some((alias) => normalizeRaftLookupValue(alias) === normalizedModel)
  );
  if (aliasMatch) return augmentOperationalTechnicalModel(aliasMatch, brand, model);

  const partialMatch = models.find((entry) => {
    const current = normalizeRaftLookupValue(entry.name);
    if (current.includes(normalizedModel) || normalizedModel.includes(current)) return true;
    return (entry.aliases || []).some((alias) => {
      const normalizedAlias = normalizeRaftLookupValue(alias);
      return normalizedAlias.includes(normalizedModel) || normalizedModel.includes(normalizedAlias);
    });
  }) || null;

  return augmentOperationalTechnicalModel(partialMatch, brand, model);
}

