export function ivaDeclarationText(norma: string) {
  return "Declara-se para os devidos efeitos fiscais que a embarcação acima identificada dedica-se à atividade " +
    "da pesca comercial, enquadrando-se nos normativos legais de isenção de IVA aplicáveis aos fornecimentos " +
    `de bens e prestação de serviços destinados a embarcações que exercem a pesca comercial (${norma}).`;
}
